-- Schema TIMMENDORF auf PDBORCL, Präfix TD_. Werkbuch Abschnitt 12, freigegeben am 31.10.2026 (F37–F49 „alle A“).
-- Teil 1 (TD_QUELLE, TD_POI, TD_NETZ_STAND, die Netze TD_NET_…) liegt in db/netz und bleibt unberührt.
--
-- Wiederholbar: Was schon da ist, meldet Oracle mit ORA-00955 (Name schon vergeben); der Einrichter der App
-- (ant dbeinrichten, Knopf „Einrichten“) übergeht genau diese Meldungen und löscht nie etwas. In SQL Developer
-- als Skript ausführen (F5); die Meldungen bei einem zweiten Lauf sind harmlos.
--
-- Hauskonvention (F30 A): Schlüssel <NAME>_ID NUMBER(10) wie in Teil 1, Sequenz TD_<NAME>_SEQ, Trigger TD_<NAME>_BIU
-- (setzt beim Einfügen Schlüssel und ANGELEGT, bei jeder Änderung GEAENDERT), nie GENERATED AS IDENTITY. Je Spalte
-- eine Zeile, damit der Einrichter fehlende Spalten erkennt und nachträgt. Geometrien in UTM 32N (SRID 25832, Meter)
-- als Flächen, Linien und Punkte in zwei Dimensionen; die Höhe steht als Zahl daneben (HOEHE, KAMERA_HOEHE).
-- Szenenmeter: x nach Osten, z nach Süden, Ursprung am Landende der Maritim Seebrücke (E 616 826, N 5 985 081).
-- Szenenzeit: SZENE_MS = ms seit 1970 wie die Uhr der App, dazu SZENE_ZEIT als TIMESTAMP WITH TIME ZONE.
-- 31 Tabellen in 6 Gruppen: Betrieb, Quellen und Befunde, Regie, Küste, Packages, Fachdaten.
-- =====================================================================================================

