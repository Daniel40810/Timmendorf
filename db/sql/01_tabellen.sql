-- -----------------------------------------------------------------------------------------------------
-- TD_BEFUND (Quellen und Befunde): Befunde des Werkbuchs je Phase: belegt, gemessen oder gestaltet [G], mit Stand (F46 A)
-- -----------------------------------------------------------------------------------------------------
CREATE SEQUENCE TD_BEFUND_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TD_BEFUND (
  BEFUND_ID  NUMBER(10) NOT NULL,
  NR         NUMBER(5) NOT NULL,
  PHASE      VARCHAR2(10),
  THEMA      VARCHAR2(80 CHAR),
  TEXT       VARCHAR2(2000 CHAR) NOT NULL,
  ART        VARCHAR2(10) NOT NULL,
  STATUS     VARCHAR2(8) DEFAULT 'OFFEN' NOT NULL,
  BEHOBEN_IN VARCHAR2(10),
  COMMIT_ID  VARCHAR2(12),
  HERKUNFT   VARCHAR2(12) DEFAULT 'EIGEN' NOT NULL,
  ANGELEGT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  GEAENDERT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT TD_BEFUND_PK PRIMARY KEY (BEFUND_ID),
  CONSTRAINT TD_BEFUND_UK UNIQUE (NR),
  CONSTRAINT TD_BEFUND_ART_CK CHECK (ART IN ('BELEGT','GEMESSEN','GESTALTET')),
  CONSTRAINT TD_BEFUND_STATUS_CK CHECK (STATUS IN ('OFFEN','BEHOBEN','BLEIBT')),
  CONSTRAINT TD_BEFUND_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT','EIGEN'))
);

CREATE OR REPLACE TRIGGER TD_BEFUND_BIU
BEFORE INSERT OR UPDATE ON TD_BEFUND
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.BEFUND_ID IS NULL THEN
      :NEW.BEFUND_ID := TD_BEFUND_SEQ.NEXTVAL;
    END IF;
    :NEW.ANGELEGT := NVL(:NEW.ANGELEGT, SYSTIMESTAMP);
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
/


COMMENT ON TABLE TD_BEFUND IS 'Timmendorf: Befunde des Werkbuchs je Phase: belegt, gemessen oder gestaltet [G], mit Stand (F46 A)';
COMMENT ON COLUMN TD_BEFUND.BEFUND_ID IS 'Schlüssel aus TD_BEFUND_SEQ';
