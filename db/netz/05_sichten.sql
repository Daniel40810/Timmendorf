CREATE OR REPLACE VIEW TD_V_NET_FUSS AS
SELECT LINK_ID, LINK_NAME AS NAME, ART, START_NODE_ID AS VON, END_NODE_ID AS NACH, COST AS LAENGE_M, ZEIT_S,
       BELAG, LICHT, BREITE, BRUECKE, EBENE, OSM_ID, GEOMETRY
  FROM TD_NET_FUSS_LINK$
/
CREATE OR REPLACE VIEW TD_V_NET_STRASSE AS
SELECT LINK_ID, LINK_NAME AS NAME, ART, START_NODE_ID AS VON, END_NODE_ID AS NACH, COST AS LAENGE_M, ZEIT_S, TEMPO,
       CASE BIDIRECTED WHEN 'N' THEN 'ja' ELSE 'nein' END AS EINBAHN, BELAG, BREITE, BRUECKE, EBENE, OSM_ID, GEOMETRY
  FROM TD_NET_STRASSE_LINK$
/
CREATE OR REPLACE VIEW TD_V_NET_BUS AS
SELECT LINK_ID, LINK_NAME AS NAME, ART, START_NODE_ID AS VON, END_NODE_ID AS NACH, COST AS LAENGE_M, ZEIT_S, TEMPO,
       CASE BIDIRECTED WHEN 'N' THEN 'ja' ELSE 'nein' END AS EINBAHN, OSM_ID, GEOMETRY
  FROM TD_NET_BUS_LINK$
/
CREATE OR REPLACE VIEW TD_V_NET_SEE AS
SELECT LINK_ID, ART, START_NODE_ID AS VON, END_NODE_ID AS NACH, COST AS LAENGE_M, ZEIT_S, ZUGANG AS TIEFE, GEOMETRY
  FROM TD_NET_SEE_LINK$
/
CREATE OR REPLACE VIEW TD_V_HALTESTELLE AS
SELECT NODE_ID, NODE_NAME AS NAME, OSM_ID, HOEHE, GEOMETRY
  FROM TD_NET_BUS_NODE$
 WHERE ART = 'haltestelle'
/
CREATE OR REPLACE VIEW TD_V_SEEZEICHEN AS
SELECT NODE_ID, NODE_NAME AS NAME, ART, OSM_ID, GEOMETRY
  FROM TD_NET_SEE_NODE$
/
DELETE FROM USER_SDO_GEOM_METADATA WHERE TABLE_NAME IN ('TD_V_NET_FUSS', 'TD_V_NET_STRASSE', 'TD_V_NET_BUS', 'TD_V_NET_SEE', 'TD_V_HALTESTELLE', 'TD_V_SEEZEICHEN')
/
INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
SELECT v.COLUMN_VALUE, 'GEOMETRY', m.DIMINFO, m.SRID
  FROM TABLE(SYS.ODCIVARCHAR2LIST('TD_V_NET_FUSS', 'TD_V_NET_STRASSE', 'TD_V_NET_BUS', 'TD_V_NET_SEE', 'TD_V_HALTESTELLE', 'TD_V_SEEZEICHEN')) v,
       USER_SDO_GEOM_METADATA m
 WHERE m.TABLE_NAME = 'TD_NET_FUSS_LINK$'
/
COMMIT
